//! The rules' numbers the UI needs too (card size, limits), written for it next to the ts-rs
//! types by `npm run types` so the UI never keeps its own copy (CLAUDE.md rule 2).

use std::fmt::Write;

use crate::canvas::{new_area, CARD_H, CARD_W, GAP, MIN_AREA};
use crate::mop::MAX_TABS;
use crate::nextup::MAX_NEXT_UP;
use crate::prefs::{DEFAULT_TIME_BUTTONS, MAX_TIME_BUTTONS, TEXT_SIZES};
use crate::windows::MAX_WINDOWS;

/// The TypeScript module.
pub fn module() -> String {
    let area = new_area(0, 0);
    let list = |v: &[u32]| v.iter().map(u32::to_string).collect::<Vec<_>>().join(", ");
    let mut out = String::from(
        "// Written by `npm run types` from crates/core (ts_constants.rs). Do not edit this file manually.\n\n",
    );
    let mut line = |doc: &str, text: String| {
        let _ = writeln!(out, "/** {doc} */\nexport const {text};");
    };
    line(
        "A card's width on the Desk, in canvas units.",
        format!("CARD_W = {CARD_W}"),
    );
    line("A card's height on the Desk.", format!("CARD_H = {CARD_H}"));
    line("The space between lined-up cards.", format!("GAP = {GAP}"));
    line(
        "The smallest project area.",
        format!("MIN_AREA = {{ w: {}, h: {} }}", MIN_AREA.0, MIN_AREA.1),
    );
    line(
        "A new project area's size.",
        format!("NEW_AREA = {{ w: {}, h: {} }}", area.w, area.h),
    );
    line(
        "Most lines on the wrap-up's list.",
        format!("MAX_NEXT_UP = {MAX_NEXT_UP}"),
    );
    line(
        "Most windows at once; opening one more closes the oldest.",
        format!("MAX_WINDOWS = {MAX_WINDOWS}"),
    );
    line(
        "Most MOPs open as tabs in the MOP notebook; opening one more closes the oldest.",
        format!("MAX_TABS = {MAX_TABS}"),
    );
    line(
        "The time buttons everyone starts with, in minutes.",
        format!("DEFAULT_TIME_BUTTONS = [{}]", list(&DEFAULT_TIME_BUTTONS)),
    );
    line(
        "Most time buttons.",
        format!("MAX_TIME_BUTTONS = {MAX_TIME_BUTTONS}"),
    );
    line(
        "Text sizes offered, in percent.",
        format!("TEXT_SIZES = [{}] as const", list(&TEXT_SIZES)),
    );
    out
}

#[cfg(test)]
mod tests {
    #[test]
    #[cfg(feature = "ts")]
    fn export_bindings_constants() {
        let dir = std::env::var("TS_RS_EXPORT_DIR").expect("set in .cargo/config.toml");
        let path = std::path::Path::new(&dir).join("constants.ts");
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(path, super::module()).unwrap();
    }

    #[test]
    fn the_module_names_every_number() {
        let m = super::module();
        for name in [
            "CARD_W = 220",
            "MIN_AREA = {",
            "MAX_NEXT_UP = 7",
            "TEXT_SIZES = [",
        ] {
            assert!(m.contains(name), "{name}");
        }
    }
}
